def get_preset(name: str) -> dict:
    """Get preset by name, returns clean_ntsc if not found."""
    return PRESETS.get(name, PRESETS["clean_ntsc"]).copy()


def get_preset_names() -> list:
    """Get list of available preset names."""
    return list(PRESETS.keys())


def get_preset_display_name(name: str) -> str:
    """Get display name for a preset."""
    preset = get_preset(name)
    return preset.get("display_name", name.replace("_", " ").title())


def apply_intensity_to_preset(preset: dict, intensity: float) -> dict:
    """Apply intensity multiplier to noise and effect parameters."""
    result = preset.copy()
    intensity_key = intensity

    if "composite_noise_intensity" in result:
        result["composite_noise_intensity"] *= intensity_key
    if "luma_noise_intensity" in result:
        result["luma_noise_intensity"] *= intensity_key
    if "chroma_noise_intensity" in result:
        result["chroma_noise_intensity"] *= intensity_key
    if "tracking_noise_noise_intensity" in result:
        result["tracking_noise_noise_intensity"] *= intensity_key
    if "snow_intensity" in result:
        result["snow_intensity"] = result["snow_intensity"] * (0.1 + 0.9 * intensity_key)
    if "chroma_phase_noise_intensity" in result:
        result["chroma_phase_noise_intensity"] *= intensity_key
    if "head_switching_horizontal_shift" in result:
        result["head_switching_horizontal_shift"] *= intensity_key
    if "vhs_edge_wave_intensity" in result:
        result["vhs_edge_wave_intensity"] *= intensity_key

    return result
